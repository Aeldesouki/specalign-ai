"""Create the faulty dataset and ground_truth.json from the baseline documents.

The spec warns against asking an LLM to rewrite the faulty OpenAPI file, because it
could introduce unplanned changes. This script makes exactly six controlled edits to
a copy of the baseline API spec and leaves requirements.docx untouched.

Usage:
    python data_generation/make_faulty.py
"""
import copy
import json
import shutil
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "sample_docs" / "baseline"
FAULTY = ROOT / "sample_docs" / "faulty"


def json_body_schema(operation: dict) -> dict:
    return operation["requestBody"]["content"]["application/json"]["schema"]


def rename_key(mapping: dict, old: str, new: str) -> dict:
    """Return a copy of mapping with one key renamed, keeping key order."""
    return {(new if key == old else key): value for key, value in mapping.items()}


def make_faulty(spec: dict) -> tuple[dict, list[dict]]:
    spec = copy.deepcopy(spec)
    paths = spec["paths"]
    truth = []

    # D01 (REQ-001): change the endpoint path /api/orders -> /api/order
    spec["paths"] = paths = rename_key(paths, "/api/orders", "/api/order")
    truth.append({"issue_id": "D01", "requirement_id": "REQ-001", "rule": "ENDPOINT_MISMATCH",
                  "expected": "/api/orders", "actual": "/api/order"})

    # D02 (REQ-002): change GET -> POST
    item = paths["/api/orders/{orderId}"]
    paths["/api/orders/{orderId}"] = rename_key(item, "get", "post")
    truth.append({"issue_id": "D02", "requirement_id": "REQ-002", "rule": "METHOD_MISMATCH",
                  "expected": "GET", "actual": "POST"})

    # D03 (REQ-003): change success response 200 -> 204
    op = paths["/api/customers/{customerId}/orders"]["get"]
    op["responses"] = rename_key(op["responses"], "200", "204")
    op["responses"]["204"]["description"] = "Customer orders request processed"
    truth.append({"issue_id": "D03", "requirement_id": "REQ-003", "rule": "STATUS_CODE_MISMATCH",
                  "expected": "200", "actual": "204"})

    # D04 (REQ-004): remove the PATCH operation (the GET for REQ-008 on the same path stays)
    del paths["/api/orders/{orderId}/status"]["patch"]
    truth.append({"issue_id": "D04", "requirement_id": "REQ-004", "rule": "MISSING_OPERATION",
                  "expected": "PATCH /api/orders/{orderId}/status", "actual": "Missing"})

    # D05 (REQ-005): rename required body field note -> comment (property AND required list)
    schema = json_body_schema(paths["/api/orders/{orderId}/notes"]["post"])
    schema["properties"] = rename_key(schema["properties"], "note", "comment")
    schema["required"] = ["comment" if f == "note" else f for f in schema["required"]]
    truth.append({"issue_id": "D05", "requirement_id": "REQ-005", "rule": "REQUIRED_FIELD_MISMATCH",
                  "expected": "note:body:string", "actual": "comment:body:string"})

    # D06 (REQ-006): change reason from string -> integer
    schema = json_body_schema(paths["/api/returns"]["post"])
    schema["properties"]["reason"]["type"] = "integer"
    truth.append({"issue_id": "D06", "requirement_id": "REQ-006", "rule": "FIELD_TYPE_MISMATCH",
                  "expected": "reason:body:string", "actual": "reason:body:integer"})

    return spec, truth


def main() -> None:
    FAULTY.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(BASELINE / "requirements.docx", FAULTY / "requirements.docx")

    baseline = yaml.safe_load((BASELINE / "openapi.yaml").read_text(encoding="utf-8"))
    faulty, truth = make_faulty(baseline)

    header = ("# FAULTY COPY: generated by data_generation/make_faulty.py from the baseline.\n"
              "# Contains six planted discrepancies (D01-D06) listed in ground_truth.json.\n")
    body = yaml.safe_dump(faulty, sort_keys=False, allow_unicode=True, width=100)
    (FAULTY / "openapi.yaml").write_text(header + body, encoding="utf-8")
    (ROOT / "ground_truth.json").write_text(json.dumps(truth, indent=2) + "\n", encoding="utf-8")
    print("Wrote sample_docs/faulty/requirements.docx (unchanged copy)")
    print("Wrote sample_docs/faulty/openapi.yaml (6 planted errors)")
    print("Wrote ground_truth.json")


if __name__ == "__main__":
    main()
